function rows(char) {
  return GLYPHS[char] ?? GLYPHS[' '];
}

export const CHAR_WIDTH = WIDTH;
export const CHAR_HEIGHT = HEIGHT;

/**
 * Renders lines of text to an RGBA buffer.
 *
 * `paperTint` gives the background a faint warm cast so the image looks like a
 * photographed receipt rather than a screenshot of a text file.
 */
export function renderText(lines, options = {}) {
  const {
    scale = 4,
    padding = 24,
    lineGap = 4,
    ink = [26, 26, 26],
    paper = [252, 251, 247],
  } = options;

  const columns = Math.max(...lines.map((line) => line.length), 1);
  const glyphW = (WIDTH + 1) * scale;
  const glyphH = HEIGHT * scale;
  const lineH = glyphH + lineGap * scale;

  const width = columns * glyphW + padding * 2;
  const height = lines.length * lineH + padding * 2;
  const pixels = Buffer.alloc(width * height * 4);

  for (let i = 0; i < width * height; i += 1) {
    pixels[i * 4] = paper[0];
    pixels[i * 4 + 1] = paper[1];
    pixels[i * 4 + 2] = paper[2];
    pixels[i * 4 + 3] = 255;
  }

  lines.forEach((line, lineIndex) => {
    const text = line.toUpperCase();
    for (let charIndex = 0; charIndex < text.length; charIndex += 1) {
      const glyph = rows(text[charIndex]);
      for (let gy = 0; gy < HEIGHT; gy += 1) {
        for (let gx = 0; gx < WIDTH; gx += 1) {
          if (glyph[gy][gx] !== '#') continue;

          const originX = padding + charIndex * glyphW + gx * scale;
          const originY = padding + lineIndex * lineH + gy * scale;

          for (let dy = 0; dy < scale; dy += 1) {
            for (let dx = 0; dx < scale; dx += 1) {
              const offset = ((originY + dy) * width + originX + dx) * 4;
              pixels[offset] = ink[0];
              pixels[offset + 1] = ink[1];
              pixels[offset + 2] = ink[2];
              pixels[offset + 3] = 255;
            }
          }
        }
      }
    }
  });

  return { pixels, width, height };
}
